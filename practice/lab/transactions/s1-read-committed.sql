-- ============================================================================
-- Сценарий 1. READ COMMITTED: грязного чтения нет, неповторяющееся — есть.
-- Две сессии. Шаги выполняются строго по номерам, [A] в первом окне, [B] во втором.
-- Перед стартом: SELECT lab.reset();
-- ============================================================================

-- [A] 1. Открываем транзакцию и снимаем деньги, НО не коммитим.
BEGIN;
UPDATE lab.accounts SET balance = balance - 500 WHERE id = 1;
SELECT id, owner, balance FROM lab.accounts ORDER BY id;   -- А видит 500 / 1000

-- [B] 2. Вторая сессия читает те же строки. Грязного чтения не будет:
--        в PostgreSQL READ UNCOMMITTED — синоним READ COMMITTED, увидеть
--        незакоммиченное невозможно в принципе.
BEGIN TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;
SELECT current_setting('transaction_isolation');           -- 'read uncommitted'
-- Уровень принят и показывается как запрошенный, но ведёт себя он ровно как
-- READ COMMITTED: в PostgreSQL нет механизма, которым можно прочитать чужую
-- незакоммиченную версию строки. Проверяем:
SELECT id, owner, balance FROM lab.accounts ORDER BY id;   -- Б видит 1000 / 1000

-- [B] 3. Не закрывая транзакцию Б, считаем сумму по системе.
SELECT sum(balance) AS total FROM lab.accounts;            -- 2000

-- [A] 4. Коммитим.
COMMIT;

-- [B] 5. Повторяем ТОТ ЖЕ запрос в ТОЙ ЖЕ транзакции.
SELECT id, owner, balance FROM lab.accounts ORDER BY id;   -- уже 500 / 1000
SELECT sum(balance) AS total FROM lab.accounts;            -- 1500 — сумма поехала
COMMIT;

-- Что увидели:
--   * грязного чтения в PostgreSQL нет ни на одном уровне;
--   * зато один и тот же запрос внутри одной транзакции дал два разных ответа —
--     это неповторяющееся чтение, штатное поведение READ COMMITTED;
--   * отчёт из нескольких запросов на этом уровне может не сойтись сам с собой.
