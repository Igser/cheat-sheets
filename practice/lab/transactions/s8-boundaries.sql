-- Сценарий 8. Границы транзакции: самая частая ошибка в реальном коде.
-- Одна сессия + наблюдение из второй.
-- Перед стартом: SELECT lab.reset(5);
-- ============================================================================

-- ---- Плохо: транзакция обнимает всё подряд ---------------------------------
-- Псевдокод, который встречается в каждом втором проекте:
--
--   $db->beginTransaction();
--   $order = $this->createOrder($cart);          // 5 мс
--   $this->paymentGateway->charge($order);       // 400-3000 мс, ЧУЖОЙ сервер
--   $this->mailer->send($order->customerEmail);  // 200 мс, ещё один чужой
--   $db->commit();
--
-- Что здесь не так:
--   * блокировки на строках заказа и остатков держатся секундами;
--   * при таймауте шлюза откатывается заказ, но деньги уже могли списаться;
--   * письмо уходит до коммита — клиент получает письмо о заказе, которого нет;
--   * пул соединений выедается: каждое ждёт чужой сервер.

-- ---- Хорошо: транзакция минимальна, внешние вызовы снаружи -----------------
-- 1) короткая транзакция: списать остаток, создать заказ, записать намерение
--    оплаты и событие в outbox;
-- 2) COMMIT;
-- 3) вызов шлюза вне транзакции, по идемпотентному ключу из шага 1;
-- 4) короткая транзакция: записать результат оплаты.

BEGIN;
WITH taken AS (
    UPDATE lab.stock SET qty = qty - 1
    WHERE product_id = 1 AND qty > 0
    RETURNING product_id
)
INSERT INTO lab.orders (product_id, buyer)
SELECT product_id, 'Алиса' FROM taken
RETURNING id, product_id, buyer;
COMMIT;
-- Всё, что могло, сделано за миллисекунды. Дальше приложение работает
-- с внешним миром, не удерживая ни одной блокировки.

-- ---- Проверка идемпотентности ----------------------------------------------
-- Повтор запроса пользователем не должен создавать второй заказ.
-- Уникальный ключ операции — самая дешёвая защита:
ALTER TABLE lab.orders ADD COLUMN IF NOT EXISTS idempotency_key text;
CREATE UNIQUE INDEX IF NOT EXISTS orders_idem_key ON lab.orders (idempotency_key)
    WHERE idempotency_key IS NOT NULL;

BEGIN;
INSERT INTO lab.orders (product_id, buyer, idempotency_key)
VALUES (1, 'Алиса', 'req-abc-123')
ON CONFLICT (idempotency_key) DO NOTHING
RETURNING id;
COMMIT;
-- Повторите этот блок второй раз: RETURNING пуст, дубля нет.
-- В приложении пустой результат означает «операция уже выполнена»,
-- нужно вернуть исходный заказ, а не ошибку.

-- ---- Наблюдение за длительностью -------------------------------------------
-- Сколько живут транзакции прямо сейчас:
SELECT * FROM lab.activity;

-- Долгие транзакции по всей базе (то, что стоит вывести на дашборд):
SELECT pid, state, now() - xact_start AS age, left(query, 60) AS query
FROM pg_stat_activity
WHERE xact_start IS NOT NULL AND now() - xact_start > interval '5 seconds'
ORDER BY age DESC;

